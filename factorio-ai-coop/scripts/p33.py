def check(st) -> list:
    sn = snap()
    ents = [e for v in st.values() for e in v]
    occ, clash = p28.occupancy(ents)
    bad = [f"겹침 {t}: {a} / {b}" for t, a, b in clash]
    deb = debris_tiles()
    bad += [f"기존 것과 겹침 {t}: {occ[t]['name']} / {sn['tiles'][t]}" for t in occ
            if t in sn["tiles"] and sn["tiles"][t] not in ("R", "X")]
    bad += [f"바위·잔해 {t} 가 DEBRIS 에 없다" for t in occ if sn["tiles"].get(t) in ("R", "X") and t not in deb]
    res = reserved()
    bad += [f"예약 칸과 겹침 {t}: {occ[t]['name']} / {res[t]}" for t in occ if t in res]
    lanes, probs = trace(ents, occ)
    bad += probs
    belt = p28.belt_map(ents)
    # 흐름: 끝까지 이어짐 · 지하 짝 · 기존 벨트는 OK_FLOWS 만 · 기존 벨트가 내 벨트로는 INFLOW 만
    for k, e in belt.items():
        if e["name"] == UG and e.get("kind") == "input":
            continue
        vx, vy = VEC[e["d"]]
        nx_ = (k[0] + vx, k[1] + vy)
        if nx_ in belt:
            continue
        how = OK_FLOWS.get((k, nx_))
        if how:
            old = sn["belts"].get(nx_)
            if old is None or old[2] != "b":
                bad.append(f"벨트 {k} -> {nx_}: 이을 기존 벨트가 스냅숏에 없다")
            elif how == "back" and old[0] != e["d"]:
                bad.append(f"벨트 {k} -> {nx_}: 뒤에서 잇기인데 기존 방향 {old[0]}")
            elif how == "side" and old[0] in (e["d"], (e["d"] + 8) % 16):
                bad.append(f"벨트 {k} -> {nx_}: 옆치기가 아니다 (기존 방향 {old[0]})")
        elif nx_ in sn["belts"]:
            bad.append(f"벨트 {k} 가 기존 벨트 {nx_} 로 흘러든다")
        elif k not in ENDS:
            bad.append(f"벨트 {k} 가 {nx_} 에서 끊긴다")
    for k in ENDS:
        if k not in belt:
            bad.append(f"끝 {k} 에 벨트가 없다")
    inflow = {a: b for a, b in INFLOW}
    for k, (d, kind, typ) in sn["belts"].items():
        if kind == "i" or typ == "s":
            continue
        vx, vy = VEC[d]
        q = (k[0] + vx, k[1] + vy)
        if q in belt and inflow.get(k) != q:
            bad.append(f"기존 벨트 {k} 가 내 벨트 {q} 로 흘러든다")
    for (a, b) in INFLOW:
        if sn["belts"].get(a, (None,))[0] is None or b not in belt:
            bad.append(f"INFLOW {a} -> {b}: 기존 벨트 또는 내 벨트가 없다")
    for k, (typ, d) in sn["arms"].items():                 # 기존 팔이 내 것을 집거나 거기 놓지 않는다
        r = 2 if typ == "l" else 1
        px, py = VEC[d]
        for t in ((k[0] + px * r, k[1] + py * r), (k[0] - px * r, k[1] - py * r)):
            if t in occ:
                bad.append(f"기존 팔 {k} 이 내 {occ[t]['name']} {t} 를 집거나 거기 놓는다")
    # 팔
    fed, outs, labs = {}, set(), set()
    for a in (e for e in ents if e["name"] in ARMS):
        sk, dk = p28.arm_ends(a)
        at = (a["x"], a["y"])
        for t, what in ((sk, "집는"), (dk, "놓는")):
            if t in res and t not in TAPS:
                bad.append(f"팔 {at} 이 예약 칸 {t} ({res[t]}) 에서 {what}다")
            if sn["tiles"].get(t) in ("R", "X") and t not in deb:
                bad.append(f"팔 {at}: {t} 에 바위·잔해")
        items, prob = picks(a, occ, lanes)
        if prob:
            bad.append(prob)
        if not items:
            bad.append(f"팔 {at}: 집을 것이 없다 ({sk})")
            continue
        src, dst = occ.get(sk), occ.get(dk)
        if src is not None and src["name"] in MACH:
            outs.add(id(src))
        if dst is not None and dst["name"] in MACH:
            want = set(RECIPE[dst["recipe"]][0]) | ({FUEL[dst["name"]]} if dst["name"] in FUEL else set())
            if not items <= want:
                bad.append(f"팔 {at}: {sorted(items - want)} 를 {dst['recipe']} 에 넣는다 (못 쓰는 것 - 팔이 선다)")
            fed.setdefault(id(dst), set()).update(items & want)
        elif dst is not None and dst["name"] in (BELT, UG):
            pass
        elif dk in sn["tiles"] and sn["tiles"][dk] == "L":
            if items != {"production-science-pack"}:
                bad.append(f"팔 {at}: 연구소 {dk} 에 {sorted(items)}")
            labs.add(dk)
        else:
            bad.append(f"팔 {at}: 놓는 칸 {dk} 에 {dst['name'] if dst else sn['tiles'].get(dk, '아무것도 없음')}")
    for m in (e for e in ents if e["name"] in MACH):
        want = set(RECIPE[m["recipe"]][0]) | ({FUEL[m["name"]]} if m["name"] in FUEL else set())
        lack = want - fed.get(id(m), set())
        if lack:
            bad.append(f"{m['recipe']} {m['x'], m['y']}: 모자람 {sorted(lack)}")
        if id(m) not in outs:
            bad.append(f"{m['recipe']} {m['x'], m['y']}: 빼는 팔 없음")
    lab_rows = {(x, y) for x in (-80, -74) for y in (22, 25, 28, 31, 34, 37, 40, 43)}
    got = {(x, y) for (x, y0) in lab_rows for y in range(y0 - 1, y0 + 2) if (x, y) in labs}
    for (x, y0) in sorted(lab_rows):
        if not any((x, y) in got for y in range(y0 - 1, y0 + 2)):
            bad.append(f"연구소 ({x},{y0}) 에 보라 팔 없음")
    # 보라가 연구소 고리까지 가나
    for k in [(LOOP_X1, LAB_L[0]), (LOOP_X2, LAB_R[-1])]:
        if lanes.get(k, {}).get("L", set()) | lanes.get(k, {}).get("R", set()) != {"production-science-pack"}:
            bad.append(f"고리 {k} 레인: {lanes.get(k)}")
    for e in ents:                                   # 채굴기 앞
        if e["name"] == EMD:
            vx, vy = VEC[e["d"]]
            if (e["x"] + 2 * vx, e["y"] + 2 * vy) not in belt:
                bad.append(f"채굴기 {e['x'], e['y']} 앞에 벨트가 없다")
    # 필터 팔 = 섞인 줄에서 집는 팔 전부 (필터 없는 섞인 줄 팔은 picks 가 잡는다)
    # 전력
    new_poles = [(e["x"], e["y"]) for e in ents if e["name"] == POLE]
    old = dict(sn["poles"])
    ps = new_poles + list(old)
    for e in ents:
        if e["name"] in POWERED and not any(abs(t[0] - p[0]) <= 2 and abs(t[1] - p[1]) <= 2 for t in tiles(e) for p in ps):
            bad.append(f"전기 없음 {e['name']} {e['x'], e['y']}")
    label = {p: {n} for p, n in old.items()}
    for p in new_poles:
        label.setdefault(p, set())
    changed = True
    while changed:
        changed = False
        for p in new_poles:
            for q, ns in label.items():
                if q != p and math.dist(p, q) <= POLE_WIRE and not ns <= label[p]:
                    label[p] |= ns
                    changed = True
    bad += [f"전봇대 {p}: 기존 망에 안 닿는다" for p in new_poles if not label[p]]
    rank = {k: i for i, k in enumerate(ORDER)}
    at = {id(e): rank[k] for k, v in st.items() for e in v}
    for a in (e for e in ents if e.get("filter")):
        early = [p for p in old] + [(e["x"], e["y"]) for e in ents if e["name"] == POLE and at[id(e)] < at[id(a)]]
        if any(abs(a["x"] - p[0]) <= 2 and abs(a["y"] - p[1]) <= 2 for p in early):
            bad.append(f"필터 팔 {a['x'], a['y']} ({a['filter']}) 이 필터보다 먼저 전기를 받는다 (기존 전봇대 또는 앞 단계)")
    for k, v in stages().items():
        if len(v) > 64:
            bad.append(f"단계 {k}: {len(v)} 스텝 > 64")
    return bad


