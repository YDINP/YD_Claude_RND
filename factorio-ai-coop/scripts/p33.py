def made(e):
    if e is None or e["name"] not in MACH:
        return None
    return RECIPE[e["recipe"]][1]


def feeders_of(belt):
    out = {}
    for k in belt:
        ins = []
        for dx, dy in VEC.values():
            q = (k[0] - dx, k[1] - dy)
            e = belt.get(q)
            if e is None or e is belt[k] or (e["name"] == UG and e.get("kind") == "input"):
                continue
            fx, fy = VEC[e["d"]]
            if (q[0] + fx, q[1] + fy) == k:
                ins.append((q, "back" if e["d"] == belt[k]["d"] else "side"))
        out[k] = ins
    return out


def ug_exit(belt, k):
    e = belt[k]
    fx, fy = VEC[e["d"]]
    for i in range(1, 6):
        q = (k[0] + fx * i, k[1] + fy * i)
        if q in belt and belt[q]["name"] == UG and belt[q].get("kind") == "output" and belt[q]["d"] == e["d"]:
            return q
    return None


def nxt(belt, k):
    e = belt[k]
    if e["name"] == UG and e.get("kind") == "input":
        q = ug_exit(belt, k)
        return [q] if q else []
    vx, vy = VEC[e["d"]]
    q = (k[0] + vx, k[1] + vy)
    return [q] if q in belt else []


def picks(a, occ, lanes):
    """팔이 집는 품목 (필터 반영) -> (품목 집합, 문제 문자열 또는 None)."""
    sk, _dk = p28.arm_ends(a)
    src = occ.get(sk)
    f = a.get("filter")
    if src is not None and src["name"] in (BELT, UG):
        have = lanes[sk]["L"] | lanes[sk]["R"]
    elif src is not None and src["name"] in MACH:
        return {made(src)}, (f"팔 {a['x'], a['y']}: 기계에서 집는데 필터 {f}" if f else None)
    elif sk in TAPS:
        have = set(TAPS[sk])
    else:
        return set(), f"팔 {a['x'], a['y']}: 집는 칸 {sk} 에 {src['name'] if src else snap()['tiles'].get(sk, '아무것도 없음')}"
    if f:
        return ({f} & have), (None if f in have else f"팔 {a['x'], a['y']}: 필터 {f} 가 집는 줄 {sorted(have)} 에 없다")
    if len(have) > 1:
        return have, f"팔 {a['x'], a['y']}: 섞인 줄 {sorted(have)} 에서 필터 없이 집는다"
    return have, None


def trace(ents, occ):
    belt = p28.belt_map(ents)
    lanes = {k: {"L": set(), "R": set()} for k in belt}
    probs = []
    for e in ents:                                   # 채굴기 -> 앞 칸 (채굴기 쪽 레인)
        if e["name"] == EMD:
            vx, vy = VEC[e["d"]]
            k = (e["x"] + 2 * vx, e["y"] + 2 * vy)
            if k in belt:
                lanes[k][p28.lane_of(belt[k]["d"], (-vx, -vy))].add(e["ore"])
    for (_src, k), v in INFLOW.items():
        for ln in "LR":
            lanes[k][ln] |= v[ln]
    feeders = feeders_of(belt)
    arms = [e for e in ents if e["name"] in ARMS]
    for _ in range(800):
        changed = False
        for a in arms:
            _sk, dk = p28.arm_ends(a)
            if dk not in belt:
                continue
            items, _p = picks(a, occ, lanes)
            sx, sy = a["x"] - dk[0], a["y"] - dk[1]
            near = p28.lane_of(belt[dk]["d"], ((sx > 0) - (sx < 0), (sy > 0) - (sy < 0)))
            if near is None:
                continue
            ln = {"L": "R", "R": "L"}[near]
            if not items <= lanes[dk][ln]:
                lanes[dk][ln] |= items
                changed = True
        for k, e in belt.items():
            ins = feeders[k]
            curve = len(ins) == 1 and ins[0][1] == "side" and e["name"] == BELT
            for q, how in ins:
                src_l = lanes[q]
                if how == "back" or curve:
                    for ln in "LR":
                        if not src_l[ln] <= lanes[k][ln]:
                            lanes[k][ln] |= src_l[ln]
                            changed = True
                else:
                    ln = p28.lane_of(e["d"], (q[0] - k[0], q[1] - k[1]))
                    allc = src_l["L"] | src_l["R"]
                    if not allc <= lanes[k][ln]:
                        lanes[k][ln] |= allc
                        changed = True
            if e["name"] == UG and e.get("kind") == "input":
                ex = ug_exit(belt, k)
                if ex:
                    for ln in "LR":
                        if not lanes[k][ln] <= lanes[ex][ln]:
                            lanes[ex][ln] |= lanes[k][ln]
                            changed = True
        if not changed:
            break
    for a in arms:
        _sk, dk = p28.arm_ends(a)
        if dk in belt:
            sx, sy = a["x"] - dk[0], a["y"] - dk[1]
            if p28.lane_of(belt[dk]["d"], ((sx > 0) - (sx < 0), (sy > 0) - (sy < 0))) is None:
                probs.append(f"팔 {a['x'], a['y']} 이 벨트 {dk} 의 앞/뒤에서 놓는다")
    for k, e in belt.items():
        if e["name"] == UG and e.get("kind") == "input":
            if ug_exit(belt, k) is None:
                probs.append(f"지하 입구 {k} 에 짝 출구가 없다 (5칸 안)")
            if any(how == "side" for _, how in feeders[k]):
                probs.append(f"지하 입구 {k} 가 옆에서 받는다")
        if e["name"] == UG and e.get("kind") == "output" and feeders[k]:
            probs.append(f"지하 출구 {k} 로 다른 벨트가 들어온다")
    for k, v in lanes.items():
        for ln in "LR":
            if len(v[ln]) > 1:
                probs.append(f"레인 섞임 {k} {ln}: {sorted(v[ln])}")
    return lanes, probs


