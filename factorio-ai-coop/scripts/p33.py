def layout() -> dict:
    """{이름: 엔티티}. 전봇대는 무리마다 앞 무리 + 기존 망 + h_poles 에서 이어 욕심 배치."""
    global _LAYOUT
    if _LAYOUT is not None:
        return _LAYOUT
    st = {k: f() for k, f in PIECES}
    occ, _ = p28.occupancy([e for v in st.values() for e in v])
    net = list(snap()["poles"]) + [(e["x"], e["y"]) for e in st["h_poles"]]
    groups = {}
    for k, _f in PIECES:
        if k in POLED:
            groups.setdefault(POLED[k], []).extend(st[k])
    for pname in POLE_GROUPS:
        ps = place_poles(groups.get(pname, []), occ, net)
        net += ps
        for x, y in ps:
            occ[(x, y)] = ent(POLE, x, y)
        st[pname] = [ent(POLE, x, y) for x, y in ps]
    _LAYOUT = st
    return st


