def path_ents(path):
    out = []
    for x, y, d, k in path:
        if k == "b":
            out.append(ent(BELT, x, y, d))
        else:
            out.append(ent(UG, x, y, d, kind="input" if k == "i" else "output"))
    return out


def ore27():
    out = [ent(FAST, TAP_X, y, E) for y in ORE_TAPS]
    out += p28.run(OB_X, ORE_TAPS[-1], OB_X, OB_Y + 1, N) + [ent(BELT, OB_X, OB_Y, W)]
    return out + p28.run(OB_X - 1, OB_Y, P27_ORE[0] + 1, OB_Y, W)


def iron():
    out = [ent(BELT, -81, Y55, E), ent(BELT, -80, Y55, E), ent(BELT, IB_X, Y55 + 1, N)]
    out += p28.run(IB_X, Y55, IB_X, IS_Y + 1, N) + [ent(BELT, IB_X, IS_Y, W)]
    return out + p28.run(IB_X - 1, IS_Y, IS_END, IS_Y, W)


def h_poles():
    return [ent(POLE, x, g) for g in GAPS for x in (SF_IN_X, SF_L_X)]


def steel():
    out = []
    for top in SF_TOPS:
        out += [ent(SFURN, SF_X, top, recipe="steel-plate"),
                ent(INS, SF_IN_X, top, W),                               # IB 에서 철 (이 칸들은 철만 - 강철은 위 (-79,-77) 에서 합류)
                ent(LONG, SF_L_X, top, E, filter="coal"),                # x=-73 에서 석탄
                ent(INS, SF_L_X, top + 1, W)]                            # 강철 -> OS
    return out


def os_line():
    bottom = SF_TOPS[-1] + 1
    out = p28.run(OS_X, bottom, OS_X, OS_TURN + 1, N) + [ent(BELT, OS_X, OS_TURN, W)]
    return out + p28.run(OS_X - 1, OS_TURN, IB_X + 1, OS_TURN, W)


def stone():
    out = [ent(EMD, x, y, N, ore="stone") for x, y in STONE_DRILLS]
    out += p28.run(STONE_DRILLS[-1][0], SB_ROW, SB_X + 1, SB_ROW, W) + [ent(BELT, SB_X, SB_ROW, S)]
    out += [ent(LONG, SB_X + 2, y, E, filter="stone-brick") for y in BRICK_ARMS]
    return out


